"""Writes docs/WALKTHROUGH.md: every step of the scenarios, with the element that acts and why, in the screen's own words.

    uv run python scripts/gen_walkthrough.py

The sentences come from `src/brain/api/static/story.js` (the table the screen reads) run over `logs/canonical/`, so the page cannot say
anything the screen does not. Needs Node. A test compares this output with the committed file.
"""

import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STORY = ROOT / "src/brain/api/static/story.js"
JS = """
const {storyOf, ROLES} = require(process.argv[1]);
const rows = [], zones = new Map();
for (const line of require("fs").readFileSync(process.argv[2], "utf8").split("\\n").filter(Boolean)) {
  const e = JSON.parse(line);
  if (e.type === "brain.started") for (const z of (e.data.topology || {}).zones || []) zones.set(z.id, {name: z.name});
  const st = storyOf(e, {zones});
  if (st) rows.push({layer: st.layer, step: st.step, tone: st.tone, quiet: !!st.quiet, say: st.say, why: st.why, type: e.type});
}
console.log(JSON.stringify({roles: ROLES, rows}));
"""
LAYER = {"TWIN": "Twin", "GUARDIAN": "Guardian", "BRAIN": "Brain", "GATE": "Safety gate", "CITY": "City"}


def story(scenario_id: str) -> dict:
    run = subprocess.run(["node", "-e", JS, str(STORY), str(ROOT / "logs/canonical" / f"{scenario_id}.jsonl")], capture_output=True, text=True, check=True)
    return json.loads(run.stdout)


def steps(rows: list[dict]) -> list[dict]:
    """What the feed shows: runs of routine readings and verdicts become one line, and a sentence repeated becomes a count."""
    out: list[dict] = []
    for row in rows:
        if row["quiet"]:
            if out and out[-1].get("run"):
                out[-1]["reads"] += row["type"] == "brain.reading.received"
                out[-1]["verdicts"] += row["type"] != "brain.reading.received"
            else:
                out.append({"run": True, "reads": int(row["type"] == "brain.reading.received"), "verdicts": int(row["type"] != "brain.reading.received"), "why": row["why"]})
        elif out and out[-1].get("say") == row["say"]:
            out[-1]["n"] += 1
        else:
            out.append({**row, "n": 1})
    return out


def cell(text: str) -> str:
    return text.replace("|", "/")


def render() -> str:
    roles = story("t12")["roles"]
    out = ["# Walkthrough: every step of the scenarios", "",
           "Generated by `scripts/gen_walkthrough.py` from the captions the screen shows (`story.js`) over `logs/canonical/`, so it says nothing the screen does not. "
           "Each row is one step: which element acts, what it does, and why it matters.", "",
           "## The five elements", "", "| Element | Its job |", "| --- | --- |"]
    out += [f"| **{r['name']}** | {r['long']} |" for r in roles]
    out += ["", "Routine readings and verdicts are folded into one row each time, as in the screen's feed.", ""]
    for path in sorted((ROOT / "scenarios").glob("t??.json")):
        spec = json.loads(path.read_text(encoding="utf-8"))
        out += [f"## {spec['id']}: {spec['name']}", "", f"**Proves:** {spec['claim'].removeprefix('Proves: ')}", "", spec["description"], "",
                f"**What the Brain should do:** {spec['expected_brain']}", "", "| # | Element | What happens | Why it matters |", "| --- | --- | --- | --- |"]
        for k, row in enumerate(steps(story(spec["id"])["rows"]), 1):
            if row.get("run"):
                reads = f"{row['reads']} reading{'s' if row['reads'] != 1 else ''}" if row["reads"] else ""
                said = (f"The Twin sends {reads}" + (f" and the Guardian judges {row['verdicts']}" if row["verdicts"] else "") + ".") if reads else f"The Guardian judges {row['verdicts']} reading{'s' if row['verdicts'] != 1 else ''}."
                element = "Twin, Guardian" if row["reads"] and row["verdicts"] else "Twin" if row["reads"] else "Guardian"
                out.append(f"| {k} | {element} | {said} | {cell(row['why'])} |")
            else:
                said = row["say"] if row["n"] == 1 else row["say"].rstrip(".") + f" ({row['n']} times)."
                out.append(f"| {k} | {LAYER[row['layer']]} | {cell(said)} | {cell(row['why'])} |")
        out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    (ROOT / "docs/WALKTHROUGH.md").write_text(render(), encoding="utf-8")
    print("wrote docs/WALKTHROUGH.md")
